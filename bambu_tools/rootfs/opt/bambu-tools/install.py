#!/usr/bin/env python3
"""Bambu Tools installer: runs inside the app every time it starts.

1. Copies the frontend bundle to /homeassistant/www/bambu-tools/ and registers it as a dashboard resource.
2. Copies the notification blueprint to /homeassistant/blueprints/automation/bambu_tools/.
3. Installs ha-bambulab (latest GitHub release) into custom_components if it is missing.
4. Creates the "Bambu" dashboard (auto-generated by the bambu-tools strategy) if it does not exist.
5. Leaves a notification in Home Assistant when a restart is needed.

Only the Python standard library is used. Talks to Home Assistant Core through the Supervisor
proxy (ws://supervisor/core/websocket) with the app's SUPERVISOR_TOKEN.
"""
import base64
import hashlib
import json
import os
import shutil
import socket
import struct
import sys
import tempfile
import time
import urllib.request
import zipfile
from pathlib import Path

HA = Path("/homeassistant")
SRC = Path("/opt/bambu-tools")
OPTIONS = Path("/data/options.json")
STATE = Path("/data/installer_state.json")
BAMBULAB_REPO = "greghesp/ha-bambulab"
DASH_PATH = "bambu-tools"


def log(msg):
    print(f"[bambu-tools] {msg}", flush=True)


def opts():
    try:
        return json.loads(OPTIONS.read_text())
    except Exception:
        return {}


def sha8(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()[:8]


def copy_if_changed(src: Path, dst: Path) -> bool:
    if dst.exists() and dst.read_bytes() == src.read_bytes():
        return False
    dst.parent.mkdir(parents=True, exist_ok=True)
    tmp = dst.with_suffix(dst.suffix + ".tmp")
    shutil.copyfile(src, tmp)
    os.replace(tmp, dst)
    return True


# ---------------- minimal websocket client (text frames, client masking) ----------------
class WS:
    def __init__(self, host="supervisor", port=80, path="/core/websocket", timeout=30):
        self.s = socket.create_connection((host, port), timeout=timeout)
        key = base64.b64encode(os.urandom(16)).decode()
        self.s.sendall((f"GET {path} HTTP/1.1\r\nHost: {host}\r\nUpgrade: websocket\r\nConnection: Upgrade\r\n"
                        f"Sec-WebSocket-Key: {key}\r\nSec-WebSocket-Version: 13\r\n\r\n").encode())
        head = b""
        while b"\r\n\r\n" not in head:
            chunk = self.s.recv(4096)
            if not chunk:
                raise ConnectionError("websocket handshake: connection closed")
            head += chunk
        status, self.buf = head.split(b"\r\n\r\n", 1)
        if b" 101 " not in status.split(b"\r\n", 1)[0]:
            raise ConnectionError(f"websocket handshake failed: {status.splitlines()[0]!r}")
        self.n = 0

    def _read(self, n):
        while len(self.buf) < n:
            chunk = self.s.recv(65536)
            if not chunk:
                raise ConnectionError("websocket closed")
            self.buf += chunk
        out, self.buf = self.buf[:n], self.buf[n:]
        return out

    def _send_frame(self, op, data: bytes):
        mask = os.urandom(4)
        n = len(data)
        head = bytearray([0x80 | op])
        if n < 126:
            head.append(0x80 | n)
        elif n < 65536:
            head.append(0x80 | 126)
            head += struct.pack("!H", n)
        else:
            head.append(0x80 | 127)
            head += struct.pack("!Q", n)
        head += mask
        self.s.sendall(bytes(head) + bytes(b ^ mask[i % 4] for i, b in enumerate(data)))

    def send(self, obj):
        self._send_frame(0x1, json.dumps(obj).encode())

    def recv(self):
        msg = b""
        while True:
            b1, b2 = self._read(2)
            op, n = b1 & 0x0F, b2 & 0x7F
            if n == 126:
                n = struct.unpack("!H", self._read(2))[0]
            elif n == 127:
                n = struct.unpack("!Q", self._read(8))[0]
            mask = self._read(4) if b2 & 0x80 else None
            payload = self._read(n)
            if mask:
                payload = bytes(b ^ mask[i % 4] for i, b in enumerate(payload))
            if op == 0x9:  # ping
                self._send_frame(0xA, payload)
                continue
            if op == 0x8:
                raise ConnectionError("websocket closed by server")
            msg += payload
            if b1 & 0x80:
                return json.loads(msg)

    def call(self, **cmd):
        self.n += 1
        cmd["id"] = self.n
        self.send(cmd)
        while True:
            m = self.recv()
            if m.get("id") == self.n and m.get("type") == "result":
                if not m.get("success"):
                    raise RuntimeError(f"{cmd.get('type')}: {m.get('error')}")
                return m.get("result")

    def close(self):
        try:
            self.s.close()
        except Exception:
            pass


def connect_core(retries=60, delay=5):
    token = os.environ.get("SUPERVISOR_TOKEN")
    if not token:
        raise RuntimeError("SUPERVISOR_TOKEN missing (homeassistant_api must be enabled)")
    last = None
    for _ in range(retries):
        try:
            ws = WS()
            first = ws.recv()
            if first.get("type") != "auth_required":
                raise ConnectionError(f"unexpected greeting {first}")
            ws.send({"type": "auth", "access_token": token})
            res = ws.recv()
            if res.get("type") != "auth_ok":
                raise PermissionError(f"auth failed: {res}")
            return ws
        except PermissionError:
            raise
        except Exception as e:  # Core still starting
            last = e
            time.sleep(delay)
    raise ConnectionError(f"Home Assistant Core not reachable: {last}")


# ---------------- steps ----------------
def install_frontend():
    src = SRC / "www" / "bambu-tools.js"
    www_existed = (HA / "www").is_dir()
    changed = copy_if_changed(src, HA / "www" / "bambu-tools" / "bambu-tools.js")
    log(f"frontend {'updated' if changed else 'up to date'} ({sha8(src)})")
    return sha8(src), not www_existed


def install_blueprint():
    for bp in (SRC / "blueprints").glob("*.yaml"):
        changed = copy_if_changed(bp, HA / "blueprints" / "automation" / "bambu_tools" / bp.name)
        log(f"blueprint {bp.name} {'updated' if changed else 'up to date'}")


def install_ha_bambulab():
    target = HA / "custom_components" / "bambu_lab"
    if (target / "manifest.json").exists():
        try:
            ver = json.loads((target / "manifest.json").read_text()).get("version")
        except Exception:
            ver = "?"
        log(f"ha-bambulab already installed ({ver}); leaving it to HACS/the user")
        return False
    log("ha-bambulab not found, downloading the latest release…")
    req = urllib.request.Request(f"https://api.github.com/repos/{BAMBULAB_REPO}/releases/latest",
                                 headers={"User-Agent": "bambu-tools-app", "Accept": "application/vnd.github+json"})
    rel = json.load(urllib.request.urlopen(req, timeout=30))
    asset = next((a for a in rel.get("assets", []) if a.get("name") == "bambu_lab.zip"), None)
    if not asset:
        raise RuntimeError(f"release {rel.get('tag_name')} has no bambu_lab.zip")
    with tempfile.TemporaryDirectory() as tmp:
        zpath = Path(tmp) / "bambu_lab.zip"
        dl = urllib.request.Request(asset["browser_download_url"], headers={"User-Agent": "bambu-tools-app"})
        with urllib.request.urlopen(dl, timeout=120) as r, open(zpath, "wb") as f:
            shutil.copyfileobj(r, f)
        out = Path(tmp) / "bambu_lab"
        with zipfile.ZipFile(zpath) as z:
            for name in z.namelist():
                dest = (out / name).resolve()
                if not str(dest).startswith(str(out.resolve())):
                    raise RuntimeError(f"unsafe path in zip: {name}")
            z.extractall(out)
        if not (out / "manifest.json").exists():
            raise RuntimeError("bambu_lab.zip has no manifest.json at its root")
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(out, target)
    log(f"ha-bambulab {rel.get('tag_name')} installed into custom_components/bambu_lab")
    return True


def register_resource(ws, version):
    url = f"/local/bambu-tools/bambu-tools.js?v={version}"
    try:
        resources = ws.call(type="lovelace/resources")
    except RuntimeError as e:
        log(f"dashboard resources not available ({e}); if dashboards are in YAML mode add {url} as a module by hand")
        return
    mine = [r for r in resources if r.get("url", "").split("?")[0] == "/local/bambu-tools/bambu-tools.js"]
    if not mine:
        ws.call(type="lovelace/resources/create", res_type="module", url=url)
        log(f"dashboard resource added: {url}")
    elif mine[0].get("url") != url:
        ws.call(type="lovelace/resources/update", resource_id=mine[0]["id"], res_type="module", url=url)
        log(f"dashboard resource updated: {url}")
    for extra in mine[1:]:
        ws.call(type="lovelace/resources/delete", resource_id=extra["id"])


def create_dashboard(ws):
    dashes = ws.call(type="lovelace/dashboards/list")
    if any(d.get("url_path") == DASH_PATH for d in dashes):
        log("dashboard 'Bambu' exists, not touching it")
        return
    ws.call(type="lovelace/dashboards/create", url_path=DASH_PATH, title="Bambu", icon="mdi:printer-3d",
            show_in_sidebar=True, require_admin=False, mode="storage")
    ws.call(type="lovelace/config/save", url_path=DASH_PATH, config={"strategy": {"type": "custom:bambu-tools"}})
    log("dashboard 'Bambu' created (/bambu-tools)")


def notify(ws, title, message, nid):
    ws.call(type="call_service", domain="persistent_notification", service="create",
            service_data={"title": title, "message": message, "notification_id": nid})


def main():
    o = opts()
    try:
        state = json.loads(STATE.read_text())
    except Exception:
        state = {}
    restart_reasons = []

    version, www_new = install_frontend()
    if www_new:
        restart_reasons.append("www")
    install_blueprint()
    if o.get("install_ha_bambulab", True):
        try:
            if install_ha_bambulab():
                restart_reasons.append("ha-bambulab")
        except Exception as e:
            log(f"could not install ha-bambulab: {e}")

    try:
        ws = connect_core()
    except Exception as e:
        log(f"cannot reach Home Assistant Core: {e}")
        return 1
    try:
        register_resource(ws, version)
        if o.get("create_dashboard", True):
            create_dashboard(ws)
        if restart_reasons:
            notify(ws, "Bambu Tools",
                   "**EN:** Bambu Tools installed " + ", ".join(restart_reasons)
                   + ". Restart Home Assistant (Settings → System → Restart), then add the **Bambu Lab** integration "
                     "(Settings → Devices & services → Add integration).\n\n"
                   "**EL:** Το Bambu Tools εγκατέστησε " + ", ".join(restart_reasons)
                   + ". Κάνε restart στο Home Assistant και μετά πρόσθεσε την integration **Bambu Lab**.",
                   "bambu_tools_restart")
        if state.get("welcomed") != version:
            notify(ws, "Bambu Tools",
                   "**EN:** Dashboard **Bambu** (sidebar), cards `bambu-layer-card` / `bambu-status-card` and the blueprint "
                   "*Bambu Tools: print notifications* are ready. Open **Bambu → Settings** to finish the set-up.\n\n"
                   "**EL:** Έτοιμα: dashboard **Bambu** στο πλάι, τα cards και το blueprint ειδοποιήσεων. "
                   "Άνοιξε **Bambu → Ρυθμίσεις** για να ολοκληρώσεις το στήσιμο.",
                   "bambu_tools_ready")
            state["welcomed"] = version
    finally:
        ws.close()
    STATE.write_text(json.dumps(state))
    log("done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
